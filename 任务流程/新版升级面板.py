import random

from 任务流程.基础任务框架 import 基础任务, 任务上下文
from 模块.检测.OCR识别器 import 安全OCR引擎


class 新版升级面板:
    """新版(2026)统一升级面板驱动

    2026年UI改版后，建筑、英雄、研究(兵种法术)、战宠四类升级全部整合为
    主村庄右侧的统一列表面板，通过面板底栏的四个入口图标切换列表。
    本类封装四类升级共用的面板操作，供各升级任务复用。

    所有坐标均为 800x600 分辨率下实测值，若游戏再次改版只需重新校准本类常量。
    """

    # ==================== 面板入口坐标常量 ====================
    建造按钮坐标 = (740, 540)       # 主村庄右下角黄色建造锤子，点击打开面板
    建筑入口坐标 = (508, 555)       # 面板底栏：建筑+英雄列表（计数 4/6）
    研究入口坐标 = (593, 555)       # 面板底栏：兵种法术研究列表（计数 1/1）
    战宠入口坐标 = (756, 555)       # 面板底栏：战宠升级列表（计数 0/1）
    面板关闭按钮坐标 = (777, 21)    # 面板右上角红色X

    # ==================== 面板列表区域常量 ====================
    面板OCR区域 = (456, 7, 800, 473)   # 右侧列表内容区域
    OCR偏移X = 456                     # OCR局部坐标换算为全屏坐标的偏移
    OCR偏移Y = 7

    # ==================== 面板内滑动常量 ====================
    面板滑动起点 = (620, 400)       # 列表内向上滑(显示更下方内容)的起点
    面板滑动步数 = 40              # 每次滑动的移动步数(约380像素，接近一屏，保留重叠不漏行)
    面板单步最小像素 = 8           # 每步移动的最小像素
    面板单步最大像素 = 11          # 每步移动的最大像素
    划到底部步数 = 40               # 打开面板后划到底部的滑动次数

    # ==================== 升级详情对话框常量 ====================
    确认按钮区域 = (514, 458, 657, 522)    # 详情对话框右下角确认按钮(含费用文字)
    确认按钮点击坐标 = (588, 493)          # 确认按钮中心
    资源不足颜色 = (250, 135, 124)         # 红色调偏粉，资源不足时费用文字颜色
    颜色检测阈值 = {'色差H': 10, '色差S': 10, '色差V': 10, '最少像素数': 150}

    # ==================== 主村庄角落计数区域常量 ====================
    工人计数OCR区域 = (693, 470, 744, 502)    # 主村庄右下角工人计数 4/6
    研究计数OCR区域 = (745, 470, 792, 502)    # 主村庄右下角研究计数 1/1

    # ==================== 战宠升级队列常量 ====================
    战宠队列条OCR区域 = (456, 45, 800, 100)   # 战宠列表顶部的升级队列条(绿色进度条+剩余时间)

    # ==================== 队伍计数解析常量 ====================
    # 游戏艺术字体的斜杠"/"常被OCR误识别成数字7，同一个"1/1"会读成"171"或"17/1"
    # 等多种变形，按字符逐一替换是补不完的，因此改为按位数约束还原，见 拆分空闲与总数
    计数字符修正表 = {
        'O': '0', 'o': '0', 'D': '0', 'Q': '0',
        'l': '1', 'I': '1', 'i': '1', '|': '1', 'L': '1',
        'Z': '2', 'z': '2',
        'S': '5', 's': '5',
        'G': '6', 'b': '6',
        'T': '7',
        'B': '8',
        'g': '9',
    }

    def __init__(self, 上下文: '任务上下文'):
        self.上下文 = 上下文
        self.OCR引擎 = 安全OCR引擎()

    # ---------------------- OCR辅助 ----------------------
    def 执行OCR识别(self, 区域) -> list:
        """对指定区域执行OCR识别，返回识别结果列表"""
        try:
            x1, y1, x2, y2 = 区域
            屏幕图像 = self.上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
            ocr结果, _ = self.OCR引擎(屏幕图像)
            return ocr结果 if ocr结果 is not None else []
        except Exception as e:
            self.上下文.置脚本状态(f"OCR识别失败: {str(e)}")
            return []

    # ---------------------- 队伍计数解析 ----------------------
    def 清理计数文本(self, 原始文本: str) -> str:
        """把计数区域的OCR文本整理成只包含数字和斜杠的字符串"""
        修正文本 = ''.join(
            self.计数字符修正表.get(字, 字)
            for 字 in 原始文本.replace(' ', '')
        )
        return ''.join(字 for 字 in 修正文本 if 字.isdigit() or 字 == '/')

    def 拆分空闲与总数(self, 清理文本: str):
        """把清理后的计数文本拆成 (空闲数, 总数)，无法拆分返回 None

        游戏内的空闲工人、研究位置、战宠位置都不超过个位数，因此两个值必定
        各占一位数字。据此可以直接按位取值，不用依赖被OCR识别错的斜杠：

            1/1  -> "1/1"    有斜杠，两侧各取第一位  -> (1, 1)
            1/1  -> "17/1"   斜杠被多识别成7粘在左侧  -> 左侧取第一位仍为 (1, 1)
            1/1  -> "171"    斜杠整体被识别成7        -> 取首尾两位      -> (1, 1)
            0/6  -> "0/6"                            -> (0, 6)
        """
        if '/' in 清理文本:
            左段, _, 右段 = 清理文本.rpartition('/')
            左字符 = 左段[0] if 左段 else ''
            右字符 = 右段[0] if 右段 else ''
        else:
            # 完全没有斜杠，说明斜杠整个变成了数字，取首尾两位即可
            if len(清理文本) < 2:
                return None
            左字符 = 清理文本[0]
            右字符 = 清理文本[-1]

        if not (左字符.isdigit() and 右字符.isdigit()):
            return None

        空闲数, 总数 = int(左字符), int(右字符)

        # 空闲数不可能大于总数，出现这种情况说明拆分位置不对
        if 空闲数 > 总数:
            return None

        return 空闲数, 总数

    def 解析队伍计数(self, 识别结果: list) -> tuple:
        """从计数区域的OCR结果解析出 (空闲数, 总数)

        OCR可能返回多个文本片段，逐个尝试直到拆出合法结果为止。
        全部失败时抛出 ValueError，由调用方决定如何处理。
        """
        if not 识别结果:
            raise ValueError("OCR识别结果为空")

        原始文本列表 = [项[1] for 项 in 识别结果]

        for 原始文本 in 原始文本列表:
            拆分结果 = self.拆分空闲与总数(self.清理计数文本(原始文本))
            if 拆分结果 is not None:
                return 拆分结果

        raise ValueError(f"无法解析计数文本：{原始文本列表}")

    # ---------------------- 面板开关 ----------------------
    def 打开列表(self, 入口坐标=None, 划到底部=False):
        """点击建造按钮打开面板，并切换到底栏指定列表入口

        :param 入口坐标: 底栏入口坐标，None 表示停留在默认的建筑列表
        :param 划到底部: 打开建筑列表后是否直接划到列表底部
        """
        self.上下文.点击(*self.建造按钮坐标, 延时=1500)
        if 入口坐标 is not None:
            self.上下文.点击(*入口坐标, 延时=1000)
        if 划到底部:
            self.滑动到列表底部()

    def 关闭面板(self):
        """点击面板右上角X关闭面板"""
        self.上下文.点击(*self.面板关闭按钮坐标, 延时=1000)

    # ---------------------- 面板内滑动 ----------------------
    def 滑动到列表底部(self):
        """连续向上滑动，把列表划到底部"""
        起点x, 起点y = self.面板滑动起点
        self.上下文.鼠标.移动到(起点x, 起点y)
        self.上下文.鼠标.左键按下()
        for _ in range(self.划到底部步数):
            self.上下文.鼠标.移动相对位置(0, random.randint(-10, -5))
            self.上下文.脚本延时(5)
        self.上下文.鼠标.左键抬起()
        self.上下文.脚本延时(1000)

    def 向上滑动一下(self):
        """列表内容上移一大格(约一屏)，显示更下方的条目"""
        起点x, 起点y = self.面板滑动起点
        self.上下文.鼠标.移动到(起点x, 起点y)
        self.上下文.鼠标.左键按下()
        for _ in range(self.面板滑动步数):
            self.上下文.鼠标.移动相对位置(0, -random.randint(self.面板单步最小像素, self.面板单步最大像素))
            self.上下文.脚本延时(3)
        self.上下文.鼠标.左键抬起()
        self.上下文.脚本延时(random.randint(250, 400))

    def 向下滑动一下(self):
        """列表内容下移一格，显示更上方的条目"""
        起点x, 起点y = self.面板滑动起点
        self.上下文.鼠标.移动到(起点x, 起点y - 200)
        self.上下文.鼠标.左键按下()
        for _ in range(self.面板滑动步数):
            self.上下文.鼠标.移动相对位置(0, random.randint(7, 12))
            self.上下文.脚本延时(5)
        self.上下文.鼠标.左键抬起()
        self.上下文.脚本延时(random.randint(300, 600))

    # ---------------------- 坐标换算 ----------------------
    def 解析行坐标(self, 坐标列表) -> tuple:
        """把OCR局部坐标框换算为全屏行区域 (左上x, 左上y, 右下x, 右下y)"""
        所有x = [点[0] for 点 in 坐标列表]
        所有y = [点[1] for 点 in 坐标列表]
        左上x = int(min(所有x)) + self.OCR偏移X
        左上y = int(min(所有y)) + self.OCR偏移Y
        右下x = self.面板OCR区域[2]
        右下y = int(max(所有y)) + self.OCR偏移Y
        return 左上x, 左上y, 右下x, 右下y

    # ---------------------- 资源检测 ----------------------
    def 检测资源不足(self, 区域: tuple) -> bool:
        """检测指定区域是否包含资源不足的红色费用文字"""
        # 延迟导入，避免与任务流程包产生循环导入
        from 任务流程.战宠升级.图像算法 import 是否包含指定颜色_HSV

        x1, y1, x2, y2 = 区域
        区域图像 = self.上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
        return 是否包含指定颜色_HSV(
            区域图像, self.资源不足颜色,
            **self.颜色检测阈值
        )

    # ---------------------- 升级确认 ----------------------
    def 确认升级(self) -> bool:
        """在升级详情对话框中检查资源并点击确认

        调用前提：已通过点击列表条目弹出升级详情对话框。
        返回 True 表示已点击确认开始升级，False 表示资源不足或未找到确认按钮。
        """
        ocr结果 = self.执行OCR识别(self.确认按钮区域)

        if "确认" not in ocr结果.__str__():
            self.上下文.置脚本状态("升级面板：未找到确认按钮")
            return False

        if self.检测资源不足(self.确认按钮区域):
            self.上下文.置脚本状态("升级面板：资源不足")
            self.关闭详情对话框()
            return False

        self.上下文.点击(*self.确认按钮点击坐标)
        return True

    def 关闭详情对话框(self):
        """关闭升级详情对话框(不关闭面板)"""
        self.上下文.键盘.按字符按压("esc")
