import time
from datetime import datetime, timedelta

import cv2
import numpy as np

from 任务流程.基础任务框架 import 任务上下文, 基础任务


class 自动捐兵任务(基础任务):
    """自动捐兵：打开部落聊天，找到带增援按钮的捐兵请求，
    在增援资源面板中把彩色（可捐）的兵种和法术逐个捐出，
    处理完一个请求继续处理下一个，最后关闭聊天窗口。

    流程依据 2026 新版界面实测：
    1. 点击主村庄左侧聊天图标打开部落聊天
    2. 聊天里的捐兵请求卡片带绿色"增援"按钮（请求：标签下方）
    3. 点增援按钮打开"增援资源"面板：彩色图标=有库存可捐，灰色=不可捐
    4. 点击彩色图标即直接捐出（无需确认，每点一次捐一个）
    5. 请求被满足后游戏会自动关闭面板，此时不需要再按返回键
    6. 若面板是被聊天刷新关掉的，回到聊天继续找下一个请求

    速度上的取舍：定位按钮优先用绿色色块（一次截图，毫秒级），
    找不到才回退到大区域 OCR；面板状态用标题小区域 OCR 校验，
    保证面板被游戏关掉后不会把村庄场景当成槽位乱点。
    """

    # ==================== 界面坐标常量 ====================
    聊天入口坐标 = (48, 300)                 # 主村庄左侧的聊天图标
    聊天消息OCR区域 = (0, 60, 320, 545)      # 聊天消息列表区域
    聊天底部OCR区域 = (0, 550, 320, 600)     # 底部输入栏(判断聊天是否打开)
    面板标题OCR区域 = (320, 140, 580, 185)   # 增援资源面板标题

    # 增援面板槽位网格(800x600实测)：7列, 前两行部队、第三行法术
    槽位列x坐标 = (340, 404, 467, 531, 594, 658, 721)
    槽位行y坐标 = (255, 338, 445)
    槽位取样半径 = 22
    面板图像区域 = (300, 130, 780, 490)      # 槽位所在的面板区域

    # 增援按钮的绿色(黄绿色,HSV实测 H≈41 S≈156 V≈222)
    按钮绿色H范围 = (25, 55)
    按钮绿色最小S = 100
    按钮绿色最小V = 150
    按钮最少绿像素 = 500

    # 快速找按钮时对绿色色块的形状约束(按钮是横条, 约130x40)
    按钮最小面积 = 2000
    按钮宽范围 = (70, 190)
    按钮高范围 = (22, 75)
    按钮中心最小x = 150
    按钮最小宽高比 = 2.0

    # ==================== 检测与限制参数 ====================
    彩色饱和度阈值 = 50       # 槽位中心平均饱和度超过该值视为彩色(可捐)
    面板打开等待毫秒 = 1200   # 点增援按钮后等面板弹出
    捐兵点击延时毫秒 = 350    # 点击自带400~600ms延时, 这里只补一点余量
    关闭面板等待毫秒 = 900
    最大捐兵点击次数 = 20     # 单个请求的点击上限(防御死循环)
    最大请求数量 = 5          # 单次任务最多处理的请求个数
    最多重开次数 = 6          # 同一请求捐几次就关面板时, 允许重开的次数
    滚动查找次数上限 = 3      # 当前屏幕没有请求时翻找更早消息的次数
    同位置判定距离 = 25       # 按钮位置几乎没变, 视为同一个请求

    def __init__(self, 上下文: '任务上下文'):
        super().__init__(上下文)
        self.已滚动次数 = 0
        self.快速定位可信 = True   # 绿色色块定位点空一次后，改用OCR定位
        self.面板打开失败 = False

    def 执行(self) -> bool:
        """任务入口"""
        try:
            # 主循环每轮都会调用本任务，未到设定间隔就直接跳过，避免每轮都开聊天
            if not self.该检查捐兵了():
                return True

            self.上下文.置脚本状态("自动捐兵：开始")

            if not self.确保聊天打开():
                self.上下文.置脚本状态("自动捐兵：无法打开聊天窗口，任务结束")
                return False

            # 聊天开起来了才算真正检查过，避免一次失败把间隔整个耗掉
            self.记录检查时间()

            处理个数 = 0
            捐出总数 = 0
            重开次数 = 0
            上次按钮坐标 = None
            上次是否捐出 = False

            while 处理个数 < self.最大请求数量:
                按钮坐标 = self.查找增援按钮()

                if 按钮坐标 is None:
                    # 面板被游戏关掉时可能连聊天也关了，先确认聊天还在
                    if not self.聊天是否打开():
                        if not self.确保聊天打开():
                            self.上下文.置脚本状态("自动捐兵：聊天窗口被关闭且无法重新打开，任务结束")
                            break
                        continue

                    # 当前屏幕没有请求，尝试翻找更早的聊天消息
                    if not self.滚动翻找请求():
                        break
                    continue

                同位置 = (
                    上次按钮坐标 is not None
                    and abs(按钮坐标[0] - 上次按钮坐标[0]) < self.同位置判定距离
                    and abs(按钮坐标[1] - 上次按钮坐标[1]) < self.同位置判定距离
                )

                # 防御：同一个请求没捐出任何东西(库存不足)，避免反复打开
                if 同位置 and not 上次是否捐出:
                    self.上下文.置脚本状态("自动捐兵：该请求没有可捐的库存，结束")
                    break

                if 同位置:
                    # 请求还没满足，游戏却把面板关了：允许再开一次继续捐
                    重开次数 += 1
                    if 重开次数 > self.最多重开次数:
                        self.上下文.置脚本状态("自动捐兵：同一请求重开面板次数过多，结束")
                        break
                else:
                    重开次数 = 0
                    处理个数 += 1

                捐出数量 = self.处理单个请求(按钮坐标)
                捐出总数 += 捐出数量
                self.已滚动次数 = 0
                上次按钮坐标 = 按钮坐标
                上次是否捐出 = 捐出数量 > 0

                if self.面板打开失败:
                    # 绿色色块可能点到了别的绿块，本次任务剩下的改用OCR定位
                    self.快速定位可信 = False
                elif 捐出数量 > 0:
                    self.快速定位可信 = True

            self.关闭聊天窗口()
            self.上下文.置脚本状态(f"自动捐兵：结束，处理{处理个数}个请求，共捐出{捐出总数}个")
            return True

        except Exception as e:
            self.异常处理(e)
            return False

    # ---------------------- 检查间隔 ----------------------
    def 该检查捐兵了(self) -> bool:
        """是否到了捐兵检查的时间

        间隔由设置里的 捐兵检查间隔(小时) 决定，0 表示每次都检查。
        记录写在 运行时状态 的 "自动捐兵检查记录" 里。
        """
        间隔小时 = self.上下文.设置.捐兵检查间隔
        if 间隔小时 <= 0:
            return True

        完整状态 = self.数据库.获取最新完整状态(self.机器人标志).状态数据
        上次记录 = 完整状态.get("自动捐兵检查记录")
        if not 上次记录:
            return True

        上次时间 = datetime.fromtimestamp(上次记录.get("时间", 0))
        间隔 = timedelta(hours=间隔小时)
        if datetime.now() - 上次时间 < 间隔:
            return False

        return True

    def 记录检查时间(self):
        """把这次检查的时间写进状态，供下一次判断间隔"""
        self.数据库.更新状态(self.机器人标志, "自动捐兵检查记录", {"时间": time.time()})

    # ---------------------- 聊天窗口操作 ----------------------
    def 聊天是否打开(self) -> bool:
        """通过底部输入栏的OCR判断聊天窗口是否打开"""
        识别结果 = self.执行OCR识别(self.聊天底部OCR区域)
        for 识别项 in 识别结果:
            文本内容 = 识别项[1]
            if "部落" in 文本内容 or "友谊" in 文本内容:
                return True
        return False

    def 确保聊天打开(self) -> bool:
        """确保部落聊天窗口已打开"""
        if self.聊天是否打开():
            return True

        self.上下文.点击(self.聊天入口坐标[0], self.聊天入口坐标[1])
        self.上下文.脚本延时(500)
        return self.聊天是否打开()

    def 关闭聊天窗口(self):
        """用返回键关闭聊天窗口回到主村庄"""
        for _ in range(2):
            if not self.聊天是否打开():
                return
            self.上下文.键盘.按字符按压("esc")
            self.上下文.脚本延时(self.关闭面板等待毫秒)

    def 滚动翻找请求(self) -> bool:
        """向下滑动聊天查看更早的消息，返回是否还可以继续滚动"""
        if self.已滚动次数 >= self.滚动查找次数上限:
            return False

        self.已滚动次数 += 1
        self.上下文.置脚本状态(f"自动捐兵：当前屏幕没有捐兵请求，翻找第{self.已滚动次数}次")
        # 手指下滑，查看更早的聊天消息
        self.上下文.滑动屏幕((160, 180), (160, 430))
        self.上下文.脚本延时(500)
        return True

    # ---------------------- 增援按钮定位 ----------------------
    def 查找增援按钮(self):
        """在聊天里定位捐兵请求的绿色增援按钮

        先用绿色色块快速定位（只截一次图，不跑OCR），
        找不到再回退到"OCR找请求：标签 + 标签下方窗口找绿色"。
        找到返回按钮中心坐标，找不到返回 None。
        """
        按钮坐标 = self.快速找绿按钮() if self.快速定位可信 else None
        if 按钮坐标 is not None:
            return 按钮坐标

        return self.用OCR找按钮()

    def 快速找绿按钮(self):
        """整块聊天区域找横条状的绿色块，返回最靠下(最新消息)的那个按钮中心"""
        x1, y1, x2, y2 = self.聊天消息OCR区域
        屏幕图像 = self.上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
        hsv图像 = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2HSV)

        下限H, 上限H = self.按钮绿色H范围
        掩码 = (
            (hsv图像[:, :, 0] >= 下限H) & (hsv图像[:, :, 0] <= 上限H)
            & (hsv图像[:, :, 1] > self.按钮绿色最小S)
            & (hsv图像[:, :, 2] > self.按钮绿色最小V)
        ).astype(np.uint8)
        掩码 = cv2.morphologyEx(掩码, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))

        块数量, _标记, 统计, 中心 = cv2.connectedComponentsWithStats(掩码, connectivity=8)

        最小宽, 最大宽 = self.按钮宽范围
        最小高, 最大高 = self.按钮高范围

        候选 = []
        for 序号 in range(1, 块数量):
            面积 = int(统计[序号, cv2.CC_STAT_AREA])
            宽 = int(统计[序号, cv2.CC_STAT_WIDTH])
            高 = int(统计[序号, cv2.CC_STAT_HEIGHT])
            if 面积 < self.按钮最小面积:
                continue
            if not (最小宽 <= 宽 <= 最大宽 and 最小高 <= 高 <= 最大高):
                continue
            if 宽 < 高 * self.按钮最小宽高比:
                continue

            中心x, 中心y = 中心[序号]
            绝对x = 中心x + x1
            if 绝对x < self.按钮中心最小x:
                continue
            候选.append((int(绝对x), int(中心y + y1)))

        if not 候选:
            return None

        # 聊天最新的消息在最下方，优先处理最靠下的按钮
        return max(候选, key=lambda 点: 点[1])

    def 用OCR找按钮(self):
        """回退方案：OCR找"请求："标签，再在其下方的固定窗口内检测绿色按钮"""
        识别结果 = self.执行OCR识别(self.聊天消息OCR区域)
        区域x1, 区域y1 = self.聊天消息OCR区域[0], self.聊天消息OCR区域[1]

        for 识别项 in 识别结果:
            文本内容 = 识别项[1]
            if "请求" not in 文本内容:
                continue

            框 = 识别项[0]
            标签y = int(min(点[1] for 点 in 框)) + 区域y1

            # 请求标签下方约40~140像素、卡片右侧区域是增援按钮的位置
            窗口x1, 窗口y1 = 180, min(标签y + 40, 545 - 100)
            窗口x2, 窗口y2 = 310, 窗口y1 + 100

            按钮坐标 = self.窗口内找绿色按钮(窗口x1, 窗口y1, 窗口x2, 窗口y2)
            if 按钮坐标 is not None:
                return 按钮坐标

        return None

    def 窗口内找绿色按钮(self, x1, y1, x2, y2):
        """在指定窗口内检测增援按钮的绿色像素块，返回按钮中心坐标"""
        屏幕图像 = self.上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
        hsv图像 = cv2.cvtColor(屏幕图像, cv2.COLOR_BGR2HSV)

        下限H, 上限H = self.按钮绿色H范围
        掩码 = (
            (hsv图像[:, :, 0] >= 下限H) & (hsv图像[:, :, 0] <= 上限H)
            & (hsv图像[:, :, 1] > self.按钮绿色最小S)
            & (hsv图像[:, :, 2] > self.按钮绿色最小V)
        )

        绿像素数 = int(掩码.sum())
        if 绿像素数 < self.按钮最少绿像素:
            return None

        ys, xs = np.nonzero(掩码)
        中心x = x1 + int(xs.mean())
        中心y = y1 + int(ys.mean())
        return (中心x, 中心y)

    # ---------------------- 增援面板操作 ----------------------
    def 处理单个请求(self, 按钮坐标) -> int:
        """点击增援按钮并捐出所有可捐的兵种法术，返回捐出数量

        注意：请求被满足后游戏会自动关闭面板，此时不能再按返回键，
        否则会把聊天窗口一起关掉。
        """
        self.上下文.置脚本状态("自动捐兵：找到捐兵请求，打开增援面板")
        self.面板打开失败 = False
        self.上下文.点击(按钮坐标[0], 按钮坐标[1])
        self.上下文.脚本延时(self.面板打开等待毫秒)

        if not self.面板是否打开():
            self.面板打开失败 = True
            self.上下文.置脚本状态("自动捐兵：增援面板未能打开，跳过该请求")
            return 0

        捐出数量 = self.捐出所有彩色槽位()

        if self.面板是否打开():
            self.上下文.键盘.按字符按压("esc")
            self.上下文.脚本延时(self.关闭面板等待毫秒)

        return 捐出数量

    def 面板是否打开(self) -> bool:
        """通过面板标题OCR判断增援资源面板是否打开"""
        识别结果 = self.执行OCR识别(self.面板标题OCR区域)
        for 识别项 in 识别结果:
            文本内容 = 识别项[1]
            if "增援" in 文本内容 or "资源" in 文本内容:
                return True
        return False

    def 获取彩色槽位(self) -> list:
        """扫描面板网格，返回彩色(可捐)槽位的坐标列表

        游戏把无库存的图标完全去色(饱和度≈0)，
        彩色图标饱和度实测在 77~138，用阈值即可干净区分。
        """
        x1, y1, x2, y2 = self.面板图像区域
        面板图像 = self.上下文.op.获取屏幕图像cv(x1, y1, x2, y2)
        hsv图像 = cv2.cvtColor(面板图像, cv2.COLOR_BGR2HSV)

        彩色槽位 = []
        for y in self.槽位行y坐标:
            for x in self.槽位列x坐标:
                cx, cy = x - x1, y - y1
                r = self.槽位取样半径
                区域 = hsv图像[cy - r:cy + r, cx - r:cx + r]
                if 区域.size == 0:
                    continue
                if 区域[:, :, 1].mean() > self.彩色饱和度阈值:
                    彩色槽位.append((x, y))
        return 彩色槽位

    def 捐出所有彩色槽位(self) -> int:
        """循环点击彩色槽位直到没有可捐的，返回捐出数量

        每点一次彩色图标捐出一个，捐完后图标会变色(库存耗尽)，
        请求被满足时游戏会直接把整个面板关掉，所以每点一次都用
        标题OCR确认面板还在，避免把村庄场景当成槽位继续乱点。
        """
        捐出数量 = 0
        while 捐出数量 < self.最大捐兵点击次数:
            彩色槽位 = self.获取彩色槽位()
            if not 彩色槽位:
                break

            x, y = 彩色槽位[0]
            self.上下文.置脚本状态(f"自动捐兵：捐出槽位 ({x},{y})，已捐{捐出数量 + 1}个")
            self.上下文.点击(x, y, 延时=self.捐兵点击延时毫秒)
            捐出数量 += 1

            if not self.面板是否打开():
                self.上下文.置脚本状态(f"自动捐兵：已捐{捐出数量}个，请求已满足，面板自动关闭")
                break

        return 捐出数量
