from 任务流程.基础任务框架 import 基础任务
from 任务流程.战宠升级.图像算法 import 是否包含指定颜色_HSV
from 任务流程.新版升级面板 import 新版升级面板


class 完成兵种或法术升级任务(基础任务):
    """完成兵种或法术升级的确认操作"""

    # ==================== 界面坐标常量（2026新版UI实测） ====================
    确认按钮区域 = (514, 458, 657, 522)
    确认按钮点击坐标 = (588, 493)

    # ==================== 检测参数常量 ====================
    资源不足颜色 = (250, 135, 124)
    颜色检测阈值 = {'色差H': 10, '色差S': 10, '色差V': 10, '最少像素数': 150}

    def __init__(self, 上下文):
        super().__init__(上下文)
        # 新版统一升级面板驱动
        self.面板 = 新版升级面板(上下文)

    def 执行(self) -> bool:
        # 判断是否够资源升级
        区域图像 = self.上下文.op.获取屏幕图像cv(*self.确认按钮区域)
        是否资源不足 = 是否包含指定颜色_HSV(
            区域图像, self.资源不足颜色,
            **self.颜色检测阈值
        )

        if 是否资源不足:
            self.上下文.置脚本状态("研究升级：资源不足")
            self._关闭升级面板()
            return False

        ocr结果 = self.执行OCR识别(self.确认按钮区域)
        if "确认" not in str(ocr结果):
            self.上下文.置脚本状态("研究升级：未找到确认按钮")
            self._关闭升级面板()
            return False

        self.上下文.点击(*self.确认按钮点击坐标)  # 点击升级
        self.上下文.脚本延时(1500)  # 等待升级详情对话框关闭
        self._关闭升级面板()
        return True

    def _关闭升级面板(self):
        """关闭升级详情对话框和新版升级面板

        新版面板用安卓返回键(esc)关不掉，必须点击面板右上角X，
        否则面板残留会阻挡后续任务对主村庄界面的识别。
        """
        self.面板.关闭详情对话框()  # esc 关闭升级详情对话框
        self.面板.关闭面板()        # 点击右上角X关闭新版面板
